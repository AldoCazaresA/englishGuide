let visited = new Set();

function getChapterIndex() {
  const params = new URLSearchParams(window.location.search);
  const ch = parseInt(params.get('ch'));
  if (!isNaN(ch) && ch >= 1 && ch <= chapters.length) return ch - 1;
  return null;
}

function ensureQuizSidebarLink() {
  const aside = document.getElementById('sidebar');
  if (!aside || document.getElementById('quizSidebarLink')) return;
  const wrap = document.createElement('div');
  wrap.className = 'sidebar-quiz-wrap';
  const a = document.createElement('a');
  a.href = 'quiz.html';
  a.id = 'quizSidebarLink';
  a.className = 'sidebar-quiz-link';
  a.textContent = 'Practice Quiz';
  wrap.appendChild(a);
  const progress = aside.querySelector('.progress-wrap');
  if (progress) aside.insertBefore(wrap, progress);
  else aside.appendChild(wrap);
}

function setQuizSidebarActive() {
  const link = document.getElementById('quizSidebarLink');
  if (!link) return;
  const path = window.location.pathname || '';
  if (/quiz\.html/i.test(path)) link.classList.add('active');
  else link.classList.remove('active');
}

function buildSidebar() {
  const list = document.getElementById('chapterList');
  if (!list) return;
  list.innerHTML = '';
  const path = window.location.pathname || '';
  const onChapterPage = /chapter\.html/i.test(path);
  const current = onChapterPage ? getChapterIndex() : null;
  chapters.forEach((ch, i) => {
    const li = document.createElement('li');
    const a = document.createElement('a');
    a.href = `chapter.html?ch=${ch.id}`;
    a.innerHTML = `<span class="ch-num">${String(ch.id).padStart(2,'0')}</span><span>${ch.title}</span>`;
    if (i === current) a.classList.add('active');
    li.appendChild(a);
    list.appendChild(li);
  });
  ensureQuizSidebarLink();
  setQuizSidebarActive();
}

